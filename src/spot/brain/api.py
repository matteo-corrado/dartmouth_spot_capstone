"""Brain interface: LLMBrain's existing public methods."""
from typing import Any, Dict, Optional, Protocol, runtime_checkable


@runtime_checkable
class Brain(Protocol):
    def is_available(self) -> bool: ...

    def wait_available(self, timeout_s: float = 90.0, poll_s: float = 2.0) -> bool: ...

    def warm_up(self) -> None: ...

    def warm_up_async(self) -> Any: ...

    def warm_up_vlm(self) -> None: ...

    def describe_persona(self, name: str) -> str: ...

    def process(self, transcript: str, state: Optional[Dict[str, Any]] = None) -> Dict[str, Any]: ...

    def query_vlm(self, image_bytes: bytes, question: str, yolo_hint: str = "") -> str: ...

    def clear_history(self) -> None: ...
